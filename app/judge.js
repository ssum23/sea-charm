/* sea-charm — 판정 엔진
 *
 * 화면과 완전히 분리된 순수 함수다. DOM도 네트워크도 쓰지 않는다.
 * 이유: 틀리면 사용자가 1천만원 이하 벌금을 문다(수산자원관리법 제65조제2호).
 *       가장 위험한 코드를 가장 단순하게 두고, 화면 없이 시험할 수 있게 한다.
 *
 * 판정 순서는 고정이다. 바꾸지 말 것 — docs/03_시스템디자인 §4.
 *   1) 어종이 자료에 없다        → 확실치 않아요
 *   2) 금어기 확정               → 놓아주세요   (길이 보지 않음)
 *   3) 지역에 따라 갈린다         → 확실치 않아요
 *   4) 길이가 없다               → 확실치 않아요
 *   5) 길이 <= 금지체장          → 놓아주세요
 *   6) 경계값(1cm 이내 초과)      → 확실치 않아요
 *   7) 그 외                    → 가져가도 돼요
 */

(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SeaCharmJudge = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var 결과 = {
    통과: '가져가도 돼요',
    방생: '놓아주세요',
    보류: '확실치 않아요'
  };

  /* ---------- 날짜 ---------- */

  // "MM-DD" → 1~366 순서값
  function md(s) {
    var p = s.split('-');
    return parseInt(p[0], 10) * 100 + parseInt(p[1], 10);
  }
  function todayMd(date) {
    return (date.getMonth() + 1) * 100 + date.getDate();
  }

  // 해를 넘기는 구간(시작 > 종료)을 처리한다. 예) 12-01 ~ 01-31
  function 기간안(구간, date) {
    var t = todayMd(date), s = md(구간.시작), e = md(구간.종료);
    if (s <= e) return t >= s && t <= e;
    return t >= s || t <= e;         // 연말을 넘어가는 경우
  }

  /* ---------- 한국어 조사·날짜 ---------- */

  // 받침 유무로 은/는, 이/가 를 고른다
  function 조사(word, 받침있을때, 받침없을때) {
    var c = word.charCodeAt(word.length - 1);
    if (c < 0xac00 || c > 0xd7a3) return 받침있을때;   // 한글이 아니면 안전한 쪽
    return ((c - 0xac00) % 28) ? 받침있을때 : 받침없을때;
  }

  // "05-01" → "5월 1일"
  function 날짜말(s) {
    var p = s.split('-');
    return parseInt(p[0], 10) + '월 ' + parseInt(p[1], 10) + '일';
  }

  /* ---------- 어종 찾기 ---------- */

  function 어종찾기(data, 이름) {
    if (!이름) return null;
    var q = String(이름).trim();
    for (var i = 0; i < data.어종.length; i++) {
      var s = data.어종[i];
      if (s.이름 === q) return s;
      if (s.별칭 && s.별칭.indexOf(q) !== -1) return s;
    }
    return null;
  }

  /* ---------- 한 지역에 적용되는 금어기 규칙 ---------- */

  function 적용규칙(species, 시도) {
    var rules = species.금어기 || [];
    var 우선 = rules.filter(function (r) {
      return r.우선 && r.시도 && r.시도.indexOf(시도) !== -1;
    });
    if (우선.length) return 우선;          // 시·도 고시가 전국 규칙을 대체한다

    return rules.filter(function (r) {
      if (r.우선) return false;
      var 전국 = r.시도 && r.시도.indexOf('전국') !== -1;
      if (전국) return (r.제외시도 || []).indexOf(시도) === -1;
      return r.시도 && r.시도.indexOf(시도) !== -1;
    });
  }

  function 금어기여부(species, 시도, date) {
    var rules = 적용규칙(species, 시도);
    for (var i = 0; i < rules.length; i++) {
      if (기간안(rules[i], date)) return rules[i];
    }
    return null;
  }

  /* ---------- 한 지역에 적용되는 금지체장 ---------- */

  function 체장기준(species, 시도) {
    var b = species.금지체장;
    if (!b) return null;
    if (b.적용시도 && b.적용시도.indexOf(시도) === -1) return null;  // 그 지역엔 규정 없음
    var 값 = b.값;
    (b.지역예외 || []).forEach(function (ex) {
      if (ex.시도 && ex.시도.indexOf(시도) !== -1) 값 = ex.값;
    });
    return { 값: 값, 단위: b.단위, 기준: b.기준, 주의: b.주의 };
  }

  /* ---------- 칭찬 사다리 (말투 가이드 §2) ---------- */

  function 칭찬(길이, 기준값, 기록) {
    기록 = 기록 || {};
    if (기록.역대최고 != null && 길이 > 기록.역대최고) return '역대 최고예요';
    if (기록.오늘최대 != null && 길이 > 기록.오늘최대) return '오늘 제일 큰 놈이에요';
    if (기준값 == null) return null;
    if (길이 >= 기준값 * 1.5) return '훌륭한 씨알이네요';
    if (길이 >= 기준값 * 1.2) return '좋은 씨알이에요';
    return null;                                   // 겨우 넘었을 땐 칭찬하지 않는다
  }

  /* ---------- 본체 ---------- */

  function 만들기(data) {
    var 시도목록 = (data.메타 && data.메타.시도목록) || [];

    function judge(입력) {
      var 날짜 = 입력.날짜 || new Date();
      var 지역 = 입력.지역 || null;
      var 길이 = (입력.길이 === '' || 입력.길이 == null) ? null : Number(입력.길이);
      var 근거 = {
        기준일: data.메타.기준일,
        법령: '수산자원관리법 시행령 별표1·별표2',
        위반시: data.메타.위반시 && data.메타.위반시.내용
      };
      var 주의 = [];

      /* 1) 어종이 자료에 없다 */
      var sp = 어종찾기(data, 입력.어종);
      if (!sp) {
        return {
          결과: 결과.보류, 단계: 2,
          이유: '이 어종은 국가 기준 자료에 없어요. 지역 조례가 있을 수 있으니 현장 안내판을 확인하세요',
          물음: null, 주의: 주의, 근거: 근거
        };
      }

      var 후보지역 = 지역 ? [지역] : 시도목록;

      /* 어종 자체에 붙은 안전 경고 (예: 복어의 독) — 판정보다 먼저 보여야 한다 */
      if (sp.경고) 주의.unshift(sp.경고);

      /* 국가 기준에 규정이 없는 어종 — 「없음」과 「모름」은 다르다.
         별표1·2 전문을 확인해 없다는 것이지, 지역 조례까지 없다는 뜻은 아니다. */
      if (sp.국가규정없음) {
        주의.push('국가 기준에는 규정이 없어요. 지역 조례가 있을 수 있으니 현장 안내판을 확인하세요');
      }

      /* 관행 방생 기준 — 법이 아니라 낚시인이 스스로 지키는 선이다.
         말투 가이드 §2-B의 규칙 셋을 그대로 따른다.
           ① 판정 줄에 넣지 않는다 — 회색 보조 줄(주의)로만
           ② 관행 미달이면 칭찬을 끈다
           ③ 판정 결과는 절대 바꾸지 않는다. 법으로 통과면 통과다
         ③이 핵심이다. 관행을 판정에 섞으면 #22(「없음」과 「모름」)가 무너진다. */
      if (sp.관행방생) {
        주의.push('낚시인들은 보통 ' + sp.관행방생.값 + sp.관행방생.단위 +
                  ' 이하는 놓아줘요 (법이 아니라 관행이에요)');
      }

      /* 좌표로만 정해지는 예외가 있으면 알려준다 (판정을 바꾸지는 않는다) */
      (sp.금어기 || []).forEach(function (r) {
        if (r.좌표예외) {
          var m = '일부 해역은 기간이 달라요' + (r.세부지역 ? ' (' + r.세부지역 + ')' : '');
          if (주의.indexOf(m) === -1) 주의.push(m);
        }
      });

      /* 2·3) 금어기 — 후보 지역 전부에서 금지면 확정, 갈리면 보류 */
      var 금지수 = 0, 걸린규칙 = null;
      후보지역.forEach(function (L) {
        var hit = 금어기여부(sp, L, 날짜);
        if (hit) { 금지수++; 걸린규칙 = 걸린규칙 || hit; }
      });

      if (금지수 === 후보지역.length && 후보지역.length > 0) {
        return {
          결과: 결과.방생, 단계: 4,
          이유: sp.이름 + 조사(sp.이름, '은 ', '는 ') + 날짜말(걸린규칙.시작) + '~' +
                날짜말(걸린규칙.종료) + '이 금어기예요. 크기와 상관없이 가져갈 수 없어요',
          금어기: 걸린규칙, 물음: null, 주의: 주의, 근거: 근거
        };
      }
      if (금지수 > 0) {
        return {
          결과: 결과.보류, 단계: 2,
          이유: '지역에 따라 금어기가 달라요',
          물음: '지역', 주의: 주의, 근거: 근거
        };
      }

      /* 3-b) 금지체장이 지역마다 다른데 지역을 모른다 */
      var 기준들 = 후보지역.map(function (L) {
        var b = 체장기준(sp, L);
        return b ? b.값 : null;
      });
      var 서로다름 = 기준들.some(function (v) { return v !== 기준들[0]; });
      if (서로다름) {
        return {
          결과: 결과.보류, 단계: 2,
          이유: '지역에 따라 기준 크기가 달라요',
          물음: '지역', 주의: 주의, 근거: 근거
        };
      }

      var 기준 = 체장기준(sp, 후보지역[0]);

      /* 체장 규정 자체가 없는 어종 */
      if (!기준) {
        return {
          결과: 결과.통과, 단계: 1,
          이유: sp.이름 + 조사(sp.이름, '은', '는') + ' 크기 제한이 없어요. 오늘은 금어기도 아니에요',
          칭찬: null, 물음: null, 주의: 주의, 근거: 근거
        };
      }

      /* 4) 길이를 모른다 */
      if (길이 == null || isNaN(길이)) {
        return {
          결과: 결과.보류, 단계: 2,
          이유: 기준.기준 + '으로 길이를 재주세요',
          물음: '길이', 기준: 기준, 주의: 주의, 근거: 근거
        };
      }

      if (기준.주의) 주의.push(기준.주의);

      /* 4-b) 상식 밖의 값 — 배 위에서 멀미·음주·장갑 낀 손으로 숫자를 누른다
         (직접다운/09_현장조사_선상낚시 §4). 상한이 없으면 250cm 참돔에
         「가져가도 돼요」가 나간다. 0 이하도 막는다.
         이 숫자(cm 200 / g 50000)는 임의로 정한 것이다 — 바꿔도 된다. */
      var 상한 = 기준.단위 === 'g' ? 50000 : 200;
      if (길이 <= 0 || 길이 > 상한) {
        return {
          결과: 결과.보류, 단계: 2,
          이유: '입력한 값이 이상해요 (' + 길이 + 기준.단위 + '). 다시 재보세요',
          물음: '길이', 기준: 기준, 주의: 주의, 근거: 근거
        };
      }

      /* 5) 기준 이하 — 「이하」가 금지다. 정확히 같은 값도 금지 */
      if (길이 <= 기준.값) {
        return {
          결과: 결과.방생, 단계: 3,
          이유: sp.이름 + ' ' + 길이 + 기준.단위 + ' · ' +
                기준.값 + 기준.단위 + ' 이하는 가져갈 수 없어요',
          기준: 기준, 물음: null, 주의: 주의, 근거: 근거
        };
      }

      /* 6) 경계 — 법이 애매해서가 아니라 사람의 측정이 부정확하기 때문 */
      if (길이 - 기준.값 <= 1) {
        return {
          결과: 결과.보류, 단계: 2,
          이유: '기준과 거의 같아요. 한 번 더 재보세요 (기준 ' + 기준.값 + 기준.단위 + ')',
          물음: '길이', 기준: 기준, 주의: 주의, 근거: 근거
        };
      }

      /* 7) 통과 — 법으로는 통과다. 다만 관행 기준에 못 미치면 칭찬만 끈다(§2-B ②) */
      var 관행미달 = !!(sp.관행방생 &&
                     기준.단위 === sp.관행방생.단위 &&
                     길이 <= sp.관행방생.값);
      return {
        결과: 결과.통과, 단계: 1,
        이유: sp.이름 + ' ' + 길이 + 기준.단위 + ' · 기준 ' + 기준.값 + 기준.단위 + ' 초과',
        칭찬: 관행미달 ? null : 칭찬(길이, 기준.값, 입력.기록),
        기준: 기준, 물음: null, 주의: 주의, 근거: 근거
      };
    }

    judge.어종목록 = function () {
      return data.어종.map(function (s) {
        return { 이름: s.이름, 별칭: s.별칭 || [], 분류: s.분류 };
      });
    };

    /* 화면 상단에 올릴 어종.
     * 인기순은 고정값이 아니라 계절 함수다 — docs/06_인기순_실측 §4.
     * 8월에 볼락이 맨 위에 있으면 「이 앱은 나를 모른다」가 된다.
     */
    judge.상단목록 = function (날짜, 개수) {
      var 달 = (날짜 || new Date()).getMonth() + 1;
      개수 = 개수 || 8;
      return data.어종
        .filter(function (s) { return s.인기; })
        .map(function (s) {
          var 제철 = !!(s.시즌 && s.시즌.indexOf(달) !== -1);
          /* 지금 금어기인 어종은 오히려 더 위에 있어야 한다.
             5월에 감성돔을 잡은 사람이 확인하려는데 목록에 없으면 검색해야 한다.
             배지를 달아 보내고, 숨기지 않는다. */
          var 금 = 금어기여부(s, '전국', 날짜 || new Date());
          if (!금 && (s.금어기 || []).length) {
            for (var i = 0; i < 시도목록.length; i++) {
              if (금어기여부(s, 시도목록[i], 날짜 || new Date())) { 금 = true; break; }
            }
          }
          return {
            이름: s.이름, 별칭: s.별칭 || [], 제철: 제철,
            금어기중: !!금, 인기: s.인기
          };
        })
        .sort(function (a, b) {
          if (a.제철 !== b.제철) return a.제철 ? -1 : 1;   // 제철이 먼저
          return a.인기 - b.인기;                          // 그 안에서 인기순
        })
        .slice(0, 개수);
    };

    judge.제철 = function (어종, 날짜) {
      var sp = 어종찾기(data, 어종);
      if (!sp || !sp.시즌) return null;
      return sp.시즌.indexOf((날짜 || new Date()).getMonth() + 1) !== -1;
    };
    judge.결과 = 결과;
    return judge;
  }

  return { 만들기: 만들기, 결과: 결과 };
});
