/* ===== 자료 무결성 ===== */
(function () {
  var 이름들 = {};
  var 문제 = [];
  data.어종.forEach(function (s) {
    if (이름들[s.이름]) 문제.push('중복 어종: ' + s.이름);
    이름들[s.이름] = true;
    (s.금어기 || []).forEach(function (g) {
      if (!g.시도) 문제.push(s.이름 + ' 금어기에 시도 없음');
      if (!/^\d{2}-\d{2}$/.test(g.시작) || !/^\d{2}-\d{2}$/.test(g.종료))
        문제.push(s.이름 + ' 날짜 형식 이상: ' + g.시작 + '~' + g.종료);
    });
    if (s.금지체장 && s.금지체장.비교 !== '이하')
      문제.push(s.이름 + ' 금지체장 비교가 「이하」가 아님');
  });
  if (!문제.length) 통과++;
  else { 실패++; 실패목록.push('  ✗ 자료 무결성\n      ' + 문제.join('\n      ')); }
})();

