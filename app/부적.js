/* sea-charm — 오늘의 바다 부적 엔진
 *
 * 화면과 분리된 순수 함수다. DOM도 네트워크도 쓰지 않는다.
 * 인터넷 없이 돌아간다 — 물때는 달의 위상 계산이고, 띠는 생년월일 계산이다.
 *
 * 겉은 부적, 속은 달과 조수다.
 *   · 물때(달의 위상)  → 오늘이 어떤 날인지를 정한다   ← 사실
 *   · 띠(생년월일)     → 그 말을 누구에게 어떻게 할지  ← 재미
 *
 * 절대 하지 않는 것 (docs/02_PRD §0)
 *   1) 어획을 예측하지 않는다 — 「잡힌다 / 못 잡는다」를 말하지 않는다
 *   2) 안전을 예언하지 않는다 — 「위험하다 / 안전하다 / 사고」를 말하지 않는다.
 *      사람이 이 말을 믿고 바다에 나가면 죽을 수 있다. 이건 재미의 영역이 아니다
 *   3) 문구는 규칙표로 고정한다 — 같은 사람이 같은 날 열면 항상 같은 부적이다
 */

