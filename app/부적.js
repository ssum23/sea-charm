  var 삭기준 = Date.UTC(2000, 0, 6, 18, 14, 0) / 86400000;  // 2000-01-06 삭(그리니치)
  var 삭망주기 = 29.530588853;

  // 삭(0)부터 며칠 지났는가. 0 ~ 29.53
  function 달나이(date) {
    var d = date.getTime() / 86400000;
    var a = (d - 삭기준) % 삭망주기;
    if (a < 0) a += 삭망주기;
    return a;
  }

  /* 음력 며칠쯤인가 — ⚠️ 근사값이다.
   * 평균 삭망주기로 계산하므로 실제 음력과 하루쯤 어긋날 수 있다.
   * 그래서 이 값은 화면에 쓰지 않는다. 물때 3단계를 정하는 데만 쓴다. */
  function 음력일(date) {
    return Math.floor(달나이(그날정오(date))) + 1;
  }

  /* 그 날짜의 정오로 맞춘다.
   * 달은 계속 움직이므로 시각을 그대로 쓰면 하루 중간에 물때 단계가 바뀐다.
   * (2026년 8~11월 120일 중 32일이 그랬다 — 아침과 저녁의 부적이 달라졌다)
   * 부적은 0시부터 24시까지 한 장이어야 하므로 **날짜만 보고 시각은 정오로 고정한다.** */
  function 그날정오(date) {
    return new Date(date.getFullYear(), date.getMonth(), date.getDate(), 12, 0, 0, 0);
  }

  /* 물때 세 단계.
   * 삭·망 무렵은 해와 달이 한 줄로 서서 조차가 가장 크고(사리),
   * 상현·하현 무렵은 서로 어긋나 조차가 가장 작다(조금).
   * 이건 관행이 아니라 천문이다. 지역마다 다르지 않다.
   */
  function 물때(date) {
    date = 그날정오(date);
    var a = 달나이(date);
    var 삭거리 = Math.min(a, 삭망주기 - a);              // 삭에서 얼마나 떨어졌나
    var 망거리 = Math.abs(a - 삭망주기 / 2);              // 망에서 얼마나 떨어졌나
    var 사리거리 = Math.min(삭거리, 망거리);
    var 조금거리 = Math.min(
      Math.abs(a - 삭망주기 / 4),
      Math.abs(a - (삭망주기 * 3) / 4)
    );
    if (사리거리 <= 2.2) return { 단계: '사리', 세기: 3, 음력일: 음력일(date) };
    if (조금거리 <= 2.2) return { 단계: '조금', 세기: 1, 음력일: 음력일(date) };
    return { 단계: '중간', 세기: 2, 음력일: 음력일(date) };
  }

  /* ---------- 물때 구간 ----------
   *
   * 부적은 하루가 아니라 **물때마다 한 장**이다 (2026-08-04 제품 결정).
   * 사리가 나흘 이어지면 그 나흘은 같은 부적이고, 물때가 바뀌면 새 부적이 나온다.
   *
   * 구간을 무엇으로 식별하는가 — 「구간이 시작된 날 + 단계」로 한다.
   * 삭망 주기 번호를 쓰면 사리가 삭 앞뒤로 걸쳐 있어서 한 구간이 둘로 쪼개진다.
   */

