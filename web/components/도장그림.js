/* 귀항 도장 — 실제 도장처럼 찍힌 모양을 코드로 그린다.
 *
 * 왜 이게 필요한가 —
 * 「왜 내일 또 여는가」를 맡은 조각이 도장이다. 그런데 지금은 동그라미 안에
 * 「무사」라는 글자만 있어서, 모아도 모은 느낌이 안 났다.
 *
 * 「무사」는 뺐다 — 무사·무사히 같은 말은 낚시를 위험한 일처럼 보이게 한다.
 * 도장은 위험을 넘겼다는 증명이 아니라 다녀왔다는 표시다 (2026-08-06 제품 결정).
 * 도장은 모으는 재미가 전부인 물건이라 생김새가 기능이다.
 *
 * ─────────────────────────────────────────────
 * 🔴 2026-08-07 — 물때마다 다른 도장 (사장님 지시)
 *
 *   「매일 똑같은 도장이면 모으는 맛이 없다. 물때마다 도장 몇 개를 정해두고
 *    그중에 하나가 나오게 하자」
 *
 *   그래서 —
 *   ① **물때 세 단계(사리·중간·조금)마다 글자 넉 장**을 뒀다. 전부 실제로 쓰는 한자다.
 *      그날의 바다가 도장에 남는다 — 사리에 다녀오면 `大潮`, 조금이면 `小潮`.
 *   ② **테두리 모양 셋**(네모·둥근·팔각)을 곱한다 → **한 물때에 12가지, 다 합쳐 36가지.**
 *   ③ 🔴 **난수를 쓰지 않는다.** 날짜에서 계산한다.
 *      난수를 쓰면 **어제 받은 도장이 오늘 다른 모양으로 바뀐다.**
 *      한 번 받은 도장은 영원히 그 도장이어야 모으는 물건이 된다.
 *   ④ 귀항을 누른 순간 고른 도장을 기록에 같이 적어둔다(`홈화면.js`).
 *      나중에 이 목록을 손대도 **이미 받은 도장은 안 바뀐다.**
 *
 * 규칙
 *  - 그림 파일이 아니라 코드다. 그림 파일을 받아오면 「외부 통신 0건」이 깨진다.
 *  - 찍히는 각도가 조금씩 다르다 — 손으로 찍으면 그렇게 된다. 이것도 날짜에서 뽑는다.
 *  - 인주색은 부적 화면이 쓰는 것과 같은 색이다(`#9c3524`). 두 조각이 한 벌로 보인다.
 *  - 「놓아주세요」의 빨강과는 다른 색이다. 도장이 경고로 읽히면 안 된다.
 */

import 부적 from '@/lib/부적엔진';

/* 부적 화면과 같은 인주색 */
export const 인주 = '#9c3524';

/* ── 도장 글자 — 물때마다 넉 장 ─────────────────────────────
 * 전부 바다·물때에서 실제로 쓰는 말이다. 지어낸 한자는 넣지 않는다.
 * 🔴 이 목록의 **순서를 바꾸거나 중간에 끼워 넣지 마라.**
 *    기록에 도장 이름이 없는 옛날 것은 순서로 되찾는다. */
export const 도장세트 = {
  사리: [
    { 글자: '歸港', 읽기: '귀항' },
    { 글자: '大潮', 읽기: '대조' }, // 사리 = 큰 물
    { 글자: '滿潮', 읽기: '만조' }, // 물이 가장 많이 든 때
    { 글자: '潮流', 읽기: '조류' }, // 물살
  ],
  중간: [
    { 글자: '歸港', 읽기: '귀항' },
    { 글자: '中潮', 읽기: '중조' }, // 사리와 조금 사이
    { 글자: '潮汐', 읽기: '조석' }, // 밀물과 썰물
    { 글자: '出漁', 읽기: '출어' }, // 고기잡이를 나감
  ],
  조금: [
    { 글자: '歸港', 읽기: '귀항' },
    { 글자: '小潮', 읽기: '소조' }, // 조금 = 작은 물
    { 글자: '干潮', 읽기: '간조' }, // 물이 가장 많이 빠진 때
    { 글자: '順風', 읽기: '순풍' }, // 가는 쪽으로 부는 바람
  ],
};

/* 테두리 모양 셋 — 같은 글자라도 다른 도장으로 보인다 */
export const 테모양 = ['네모', '둥근', '팔각'];

/* 다 합쳐 몇 가지인가 — 홈에서 「N종 중 M종」을 세는 데 쓴다 */
export const 도장가짓수 =
  Object.values(도장세트).reduce((합, l) => 합 + l.length, 0) * 테모양.length;

/* 날짜에서 숫자 하나를 뽑는다. 같은 날이면 언제 봐도 같은 값이다.
 *
 * 🔴 여기서 두 번 넘어졌다. 둘 다 「곱하고 나머지」 방식의 함정이다 —
 *   ① 섞는 수와 나누는 수가 같으면 **언제나 0**이 나온다(테두리가 전부 네모였다).
 *   ② 그걸 고쳐도, 날짜를 **사흘씩 건너뛰며** 보면 값이 3의 배수로만 움직여
 *      **셋으로 나눈 나머지가 안 바뀐다**(테두리가 또 전부 네모였다).
 *
 * 그래서 「곱하고 나머지」를 버리고 **섞기 함수**를 쓴다.
 * 날짜가 하루만 달라도 결과가 통째로 흩어진다. 규칙성이 남지 않는다.
 */
function 씨앗(날짜, 섞기) {
  let h =
    (날짜.getFullYear() * 10000 + (날짜.getMonth() + 1) * 100 + 날짜.getDate()) ^ 섞기;
  h = Math.imul(h ^ (h >>> 15), 2246822507);
  h = Math.imul(h ^ (h >>> 13), 3266489909);
  return (h ^ (h >>> 16)) >>> 0;
}

/* 🔴 이 날의 도장은 무엇인가 — 날짜만 있으면 언제나 같은 답이 나온다 */
export function 도장고르기(날짜) {
  const d = 날짜 instanceof Date ? 날짜 : new Date(날짜);
  let 단계 = '중간';
  try {
    단계 = 부적.물때(d).단계 || '중간';
  } catch (e) {
    /* 물때 계산이 실패해도 도장은 찍혀야 한다 */
  }
  const 목록 = 도장세트[단계] || 도장세트.중간;
  const 글자칸 = 씨앗(d, 0x9e37) % 목록.length;
  const 테칸 = 씨앗(d, 0x85eb) % 테모양.length;
  return {
    단계,
    ...목록[글자칸],
    테: 테모양[테칸],
    /* 기록에 적어두는 이름표. 「사리-1-둥근」 처럼 생겼다 */
    아이디: `${단계}-${글자칸}-${테모양[테칸]}`,
  };
}

/* 기록에 적힌 이름표를 다시 도장으로 되돌린다.
   못 알아보면 null 을 준다 — 그러면 날짜로 다시 계산한다 */
export function 아이디로(아이디) {
  if (typeof 아이디 !== 'string') return null;
  const [단계, 칸, 테] = 아이디.split('-');
  const 목록 = 도장세트[단계];
  const it = 목록 && 목록[Number(칸)];
  if (!it || !테모양.includes(테)) return null;
  return { 단계, ...it, 테, 아이디 };
}

/* 손으로 찍은 것처럼 조금씩 기울인다.
   같은 날짜면 언제 봐도 같은 각도여야 하므로 날짜에서 뽑는다. */
function 기울기(날짜) {
  const 씨 = 날짜.getFullYear() * 372 + (날짜.getMonth() + 1) * 31 + 날짜.getDate();
  return ((씨 * 7) % 11) - 5; // -5도 ~ +5도
}

/* 번짐 무늬가 도장마다 같으면 줄지어 놓았을 때 복사한 것처럼 보인다. */
function 번짐씨(날짜) {
  const 씨 = 날짜.getFullYear() + (날짜.getMonth() + 1) * 12 + 날짜.getDate();
  return 씨 % 90;
}

/* 팔각형 — 네 귀퉁이를 잘라낸 모양 */
function 팔각(안쪽) {
  const a = 안쪽 ? 14 : 5;
  const b = 안쪽 ? 86 : 95;
  const c = (b - a) * 0.29; // 잘라내는 길이
  return [
    [a + c, a], [b - c, a], [b, a + c], [b, b - c],
    [b - c, b], [a + c, b], [a, b - c], [a, a + c],
  ].map((p) => p.join(',')).join(' ');
}

/* 테두리 한 겹 그리기 */
function 테그리기(모양, 안쪽, 굵기, 흐림) {
  const 공통 = { strokeWidth: 굵기, opacity: 흐림 };
  if (모양 === '둥근') {
    return <circle cx="50" cy="50" r={안쪽 ? 36 : 45} {...공통} />;
  }
  if (모양 === '팔각') {
    return <polygon points={팔각(안쪽)} {...공통} />;
  }
  return (
    <rect
      x={안쪽 ? 14 : 5}
      y={안쪽 ? 14 : 5}
      width={안쪽 ? 72 : 90}
      height={안쪽 ? 72 : 90}
      rx={안쪽 ? 5 : 10}
      {...공통}
    />
  );
}

export default function 도장그림({
  날짜,
  크기: 그림크기 = 56,
  색깔 = 인주,
  도장,          // 기록에 적어둔 도장. 없으면 날짜로 계산한다
  글자,          // 이것만 따로 주면 그 글자로 찍는다 (부적 화면에서 쓴다)
}) {
  const d = 날짜 instanceof Date ? 날짜 : new Date(날짜 || Date.now());
  const 고른것 = 도장 || 도장고르기(d);
  const 두글자 = (글자 || 고른것.글자).slice(0, 2);
  const 각 = 기울기(d);
  const 이름표 = `도장번짐-${d.getFullYear()}${d.getMonth() + 1}${d.getDate()}-${고른것.테}`;
  const 씨 = 번짐씨(d);
  /* 둥근 테는 안쪽이 좁아 글자를 조금 줄여야 테에 닿지 않는다 */
  const 글씨 = 고른것.테 === '둥근' ? 27 : 30;

  return (
    <svg
      viewBox="0 0 100 100"
      width={그림크기}
      height={그림크기}
      role="img"
      aria-label={`귀항 도장 — ${두글자} (${고른것.읽기 || ''})`}
      style={{ transform: `rotate(${각}deg)`, display: 'block', overflow: 'visible' }}
    >
      <defs>
        {/* 인주가 종이에 번진 것처럼 테두리를 살짝 흩는다 */}
        <filter id={이름표} x="-20%" y="-20%" width="140%" height="140%">
          <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" seed={씨} result="무늬" />
          <feDisplacementMap in="SourceGraphic" in2="무늬" scale="1.5" xChannelSelector="R" yChannelSelector="G" />
        </filter>
      </defs>

      <g filter={`url(#${이름표})`} fill="none" stroke={색깔}>
        {테그리기(고른것.테, false, 6, 1)}
        {테그리기(고른것.테, true, 1.6, 0.75)}
        {/* 두 글자를 나누는 가로선 — 아주 흐리게 */}
        <line x1="20" y1="50" x2="80" y2="50" strokeWidth="1" opacity="0.26" />
      </g>

      {/* 두 글자를 위에서 아래로. 네 글자보다 두 글자가 훨씬 커져서 작게 놓아도 읽힌다.
          🔴 글자 아래끝(baseline) 기준 + `dy` 로 내린다 —
          `dominantBaseline` 은 **사파리가 안 지켜서** 아이폰에서만 위로 쏠렸다(2026-08-06). */}
      <g
        filter={`url(#${이름표})`}
        fill={색깔}
        fontSize={글씨}
        fontWeight="700"
        textAnchor="middle"
      >
        <text x="50" y="32" dy="0.35em">{두글자[0]}</text>
        <text x="50" y="68" dy="0.35em">{두글자[1] || ''}</text>
      </g>
    </svg>
  );
}
