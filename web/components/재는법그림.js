/* 재는 법 그림 — 어디서 어디까지 재는지 보여준다.
 *
 * 왜 이게 필요한가 —
 * 갈치는 「항문장」으로 잰다. 주둥이 끝에서 항문까지다. 꼬리까지 재면
 * 실제보다 두 배 가까이 길게 나와서, 놓아줘야 할 갈치에 「가져가도 돼요」가 뜬다.
 * 글로만 「항문장으로 재세요」라고 쓰면 대부분 그냥 전체 길이를 잰다.
 * 그림 한 장이 판정 하나를 살린다 — 시스템디자인 §5 「글을 읽기 전에 안다」.
 *
 * 규칙
 *  - 그림은 파일이 아니라 코드다. 외부에서 받아오는 그림이 하나라도 있으면
 *    「외부 통신 0건」이 깨진다(시스템디자인 §8).
 *  - 색은 currentColor 만 쓴다. 화면 색이 바뀌어도 따라간다.
 *  - 재는 구간은 굵은 선 + 양끝 표시, 재지 않는 부분은 흐린 선.
 *    「어디까지」가 한눈에 보여야 한다.
 *  - 기준 이름을 모르면 그림을 그리지 않고 글 안내만 남긴다(틀린 그림보다 없는 게 낫다).
 */

const 몸선 = { fill: 'none', stroke: 'currentColor', strokeWidth: 1.6, opacity: 0.45 };
const 잰선 = { stroke: 'currentColor', strokeWidth: 2.4, strokeLinecap: 'round' };
const 끝선 = { stroke: 'currentColor', strokeWidth: 2.4, strokeLinecap: 'round' };

/* 재는 구간 — 굵은 가로선 + 양끝 세로 막대 */
function 가로자({ x1, x2, y = 88, 높이 = 7 }) {
  return (
    <g>
      <line x1={x1} y1={y} x2={x2} y2={y} {...잰선} />
      <line x1={x1} y1={y - 높이} x2={x1} y2={y + 높이} {...끝선} />
      <line x1={x2} y1={y - 높이} x2={x2} y2={y + 높이} {...끝선} />
    </g>
  );
}

/* 재는 구간 — 굵은 세로선 + 양끝 가로 막대 */
function 세로자({ y1, y2, x = 34, 너비 = 7 }) {
  return (
    <g>
      <line x1={x} y1={y1} x2={x} y2={y2} {...잰선} />
      <line x1={x - 너비} y1={y1} x2={x + 너비} y2={y1} {...끝선} />
      <line x1={x - 너비} y1={y2} x2={x + 너비} y2={y2} {...끝선} />
    </g>
  );
}

/* 자와 몸의 어느 점이 짝인지 잇는 흐린 점선.
   이게 없으면 「자가 몸의 어디를 가리키는지」가 애매하다 */
function 안내선({ x1, y1, x2, y2 }) {
  return (
    <line
      x1={x1} y1={y1} x2={x2} y2={y2}
      stroke="currentColor" strokeWidth="1" strokeDasharray="2 3" opacity="0.3"
    />
  );
}

