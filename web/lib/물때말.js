/* 물때 이름을 쉬운 말로 풀어주는 곳.
 *
 * 왜 필요한가 —
 * 「조금」은 바다 용어인데 일상어 「조금만」과 글자가 똑같다.
 * 그래서 「조금」이라고만 적어두면 「조금(=약간)」으로 읽힌다.
 * 「사리」도 처음 보면 무슨 말인지 모른다.
 * (2026-08-06 수민님이 「조금이 무슨 뜻인지 모르겠다」고 알려줬다)
 *
 * 고른 방법 — 진짜 용어를 그대로 쓰고, 이름 뒤에 짧은 풀이를 항상 붙인다.
 * 용어를 쉬운 말로 갈아치우지 않는 이유: 배 타는 사람들이 실제로 쓰는 말이
 * 「사리」·「조금」이다. 앱이 그 말을 없애면 대화가 안 통한다.
 *
 * 물때가 왜 생기나 —
 * 달과 해가 한 줄로 서면(보름·그믐) 밀물과 썰물의 차가 가장 커진다 → 사리.
 * 달이 반쯤 찼을 때(반달) 그 차가 가장 작아진다 → 조금. 그 사이가 중간.
 * 이 계산은 `app/부적.js` 가 달의 위상으로 직접 한다(인터넷을 쓰지 않는다).
 *
 * 🔴 어획이나 안전을 말하지 않는다. 물이 얼마나 움직이는지만 말한다.
 *    「물이 세니 잘 잡힌다」는 말은 넣지 않는다 — 그건 예언이다.
 */

/* 이름 뒤에 붙이는 한 줄 */
export const 풀이 = {
  사리: '물살이 한 달 중 가장 세요',
  중간: '물살이 무리 없이 흘러요',
  조금: '물살이 한 달 중 가장 약해요',
};

/* 자리가 좁을 때 쓰는 짧은 말 */
export const 짧게 = {
  사리: '센 물',
  중간: '보통 물',
  조금: '약한 물',
};

/* 「조금 · 약한 물」 — 좁은 자리용 */
export function 이름과짧게(단계) {
  if (!단계) return '';
  return 짧게[단계] ? `${단계} · ${짧게[단계]}` : 단계;
}
