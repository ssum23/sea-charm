/* 해역별 제철 — 동해·서해·남해·제주
 *
 * 왜 이게 필요한가 —
 * 「8월에 많이 잡히는 것」이 전국 기준이라, **서해 낚시인에게 갈치가 뜨고 동해 낚시인에게 주꾸미가 떴다.**
 * 실제로는 주꾸미 어획의 **거의 전부가 서해**이고, 동해에서는 거의 안 잡힌다.
 *
 * 자료 — 낚시어선어획량조사(KOSIS·해양수산부) **시도별 × 어종별 × 월별** 40개월치.
 * 사장님이 직접 받아 주셨다. 어종별 총괄만 있던 전 자료로는 만들 수 없었다.
 *
 * 🔴 이 값은 **판정에 쓰이지 않는다.**
 *    어느 달에 많이 잡히는지일 뿐이고, **가져가도 되는지와는 아무 관계가 없다.**
 *    금어기·금지체장은 지금처럼 전국 기준 + 지역 규칙 있는 14종만 본다.
 */

import 자료 from '../../app/해역시즌.json';

export const 해역들 = 자료.해역;                 // ['동해','서해','남해','제주']
export const 제철문턱 = 자료.제철문턱 || 30;
export const 해역메타 = 자료.메타;

/* 그 해역에서 그 어종을 말할 수 있나 — 자료가 너무 적으면 null 이다 */
export function 해역값(이름, 해역) {
  if (!해역) return null;
  const 칸 = 자료.어종[이름];
  return (칸 && 칸[해역]) || null;
}

/* 이 달, 이 해역에서 얼마나 잡히나 — 0~100. 가장 많은 달이 100이다.
   자료가 없으면 null 을 준다(0이 아니다 — 「없다」와 「모른다」는 다르다) */
export function 이달몫(이름, 해역, 달) {
  const v = 해역값(이름, 해역);
  if (!v || !v.월) return null;
  return v.월[달 - 1];
}

/* 🔴 2026-08-07 (2) — 통계만 믿지 않는다 (사장님 지적)
 *
 * 「통계에 많이 잡혔다」와 「낚시인이 말하는 시즌」은 **서로 다른 것을 잰다.**
 *   통계  = 낚시어선이 그 달에 잡아 온 마릿수 (2023~2026 실측)
 *   시즌  = 그 어종을 노리러 가는 때 (경험·관습)
 * 27종을 맞춰보니 **16종은 맞고 11종이 어긋났다.**
 * 어느 한쪽이 틀린 게 아니라 **서로 다른 것을 재고 있다.**
 *
 * 그래서 어느 쪽도 버리지 않는다 —
 *   '제철'  두 자료가 **함께** 그 달을 가리킨다. 가장 믿을 만하다
 *   '많이'  통계만 가리킨다. 그 바다 그 달에 많이 잡히는 것은 **사실이다**
 *   null    통계가 그 달을 가리키지 않는다
 *
 * 🔴 커뮤니티 글 하나로 실측을 뒤집지 않는다.
 *    한 블로그는 학공치를 6~10월이라 했지만 우리 실측은 **1월이 9월의 44배**다.
 *    전문지 자료는 「덮는 것」이 아니라 「겹칠 때 더 힘을 싣는 것」으로만 쓴다.
 */
export function 전문지월(이름) {
  const v = 자료.전문지 && 자료.전문지[이름];
  return v ? v.월 : null;
}

export function 해역제철(이름, 해역, 달) {
  const m = 이달몫(이름, 해역, 달);
  if (m == null || m < 제철문턱) return null;
  const ㅈ = 전문지월(이름);
  if (ㅈ && ㅈ.indexOf(달) !== -1) return '제철';
  return '많이';
}

/* 그 해역에서 자료가 있는 어종인가 — 없으면 목록에서 뒤로 보낸다 */
export function 해역에있나(이름, 해역) {
  return !!해역값(이름, 해역);
}
