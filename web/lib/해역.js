/* 해역별 제철 — 동해·서해·남해·제주
 *
 * 왜 이게 필요한가 —
 * 「8월에 많이 잡히는 것」이 전국 기준이라, **서해 낚시인에게 갈치가 뜨고 동해 낚시인에게 주꾸미가 떴다.**
 * 실제로는 주꾸미 어획의 **거의 전부가 서해**이고, 동해에서는 거의 안 잡힌다.
 *
 * 자료 — 낚시어선어획량조사(KOSIS·해양수산부) **시도별 × 어종별 × 월별** 40개월치.
 * 사장님이 직접 받아 주셨다. 어종별 총괄만 있던 전 자료로는 만들 수 없었다.
 *
 * 🔴 이 값은 **판정에 쓰이지 않는다.**
 *    어느 달에 많이 잡히는지일 뿐이고, **가져가도 되는지와는 아무 관계가 없다.**
 *    금어기·금지체장은 지금처럼 전국 기준 + 지역 규칙 있는 14종만 본다.
 */

import 자료 from '../../app/해역시즌.json';

export const 해역들 = 자료.해역;                 // ['동해','서해','남해','제주']
export const 제철문턱 = 자료.제철문턱 || 30;
export const 해역메타 = 자료.메타;

/* 그 해역에서 그 어종을 말할 수 있나 — 자료가 너무 적으면 null 이다 */
export function 해역값(이름, 해역) {
  if (!해역) return null;
  const 칸 = 자료.어종[이름];
  return (칸 && 칸[해역]) || null;
}

/* 이 달, 이 해역에서 얼마나 잡히나 — 0~100. 가장 많은 달이 100이다.
   자료가 없으면 null 을 준다(0이 아니다 — 「없다」와 「모른다」는 다르다) */
export function 이달몫(이름, 해역, 달) {
  const v = 해역값(이름, 해역);
  if (!v || !v.월) return null;
  return v.월[달 - 1];
}

/* 이 해역에서 이 달이 제철인가 */
export function 해역제철(이름, 해역, 달) {
  const m = 이달몫(이름, 해역, 달);
  return m == null ? null : m >= 제철문턱;
}

/* 그 해역에서 자료가 있는 어종인가 — 없으면 목록에서 뒤로 보낸다 */
export function 해역에있나(이름, 해역) {
  return !!해역값(이름, 해역);
}
