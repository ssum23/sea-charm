/* 헷갈림 주의 — 「고른 어종이 실은 다른 것일 때 판정이 느슨해지는가」
 *
 * 왜 필요한가 (2026-08-10) —
 * 어종을 잘못 고르면 **금어기와 금지체장이 통째로 바뀐다.**
 * 5월에 감성돔을 참돔으로 고르면 「가져가도 됩니다」가 뜨는데 실제로는 위반이다.
 * 🔴 **이 오류는 길이를 아무리 잘 재도 못 막는다.**
 *
 * 🔴 이건 어종 자동 인식과 상관없다. **사람이 직접 고를 때도 똑같이 헷갈린다.**
 *    자동 인식은 첫 버전에 없다(PRD §0-2). 이 안내는 지금 당장 쓰인다.
 *
 * 🔴 판정을 바꾸지 않는다. **결과·단계·순서는 그대로고, 아래에 한 줄이 붙을 뿐이다.**
 *    법으로 통과면 통과다. 우리가 「혹시 다른 고기 아니냐」고 대신 정하지 않는다.
 */

import 자료 from '../../app/헷갈림.json';

export const 헷갈림메타 = 자료.메타;

/* 🔴 조사(은/는 · 이었다/였다)를 이름에 맞춘다.
 *
 * 「감성돔는」이 아니라 「감성돔은」이다. 받침이 있으면 은/이었다, 없으면 는/였다.
 * 한글 낱자는 0xAC00 부터 28개씩 묶여 있고, 그 안에서 받침이 0이면 받침이 없다.
 * 🔴 사람에게 보이는 말이다. 어색하면 앱 전체가 어설퍼 보인다. */
export function 받침있나(말) {
  if (!말) return false;
  const 끝 = String(말).trim().slice(-1);
  const 코드 = 끝.charCodeAt(0);
  if (코드 < 0xac00 || 코드 > 0xd7a3) return false;   // 한글이 아니면 없는 것으로 본다
  return (코드 - 0xac00) % 28 !== 0;
}
export const 은는 = (말) => 말 + (받침있나(말) ? '은' : '는');
export const 이었 = (말) => 말 + (받침있나(말) ? '이었다면' : '였다면');

/* 그 날짜에 그 어종이 금어기인가 — species.json 의 금어기 칸을 그대로 읽는다.
   🔴 여기서 날짜 규칙을 새로 만들지 않는다. 판정 엔진과 같은 자료를 본다 */
function 금어기인가(어종칸, 날짜) {
  const 목록 = (어종칸 && 어종칸.금어기) || [];
  if (!목록.length) return false;
  const 월 = 날짜.getMonth() + 1;
  const 일 = 날짜.getDate();
  const 숫자 = 월 * 100 + 일;
  for (const 구간 of 목록) {
    const [시월, 시일] = String(구간.시작).split('-').map(Number);
    const [끝월, 끝일] = String(구간.종료).split('-').map(Number);
    const 시 = 시월 * 100 + 시일;
    const 끝 = 끝월 * 100 + 끝일;
    /* 해를 넘기는 금어기(예: 12-01 ~ 01-31)도 있다 */
    if (시 <= 끝 ? 숫자 >= 시 && 숫자 <= 끝 : 숫자 >= 시 || 숫자 <= 끝) return true;
  }
  return false;
}

/* 화면에 띄울 주의 목록을 만든다.
 *
 *   고른어종 : 사람이 고른 이름
 *   길이     : 사람이 잰 값 (cm). 없으면 null
 *   날짜     : 오늘
 *   어종찾기 : (이름) => species.json 의 그 칸
 *
 * 🔴 「정말 위험할 때만」 띄운다 —
 *    · 금어기 : 실제 후보가 **오늘 금어기**일 때만
 *    · 기준   : 잰 길이가 **실제 후보의 기준 이하**일 때만 (그때만 판정이 뒤집힌다)
 *    그 밖에는 아무 말도 하지 않는다. 자주 뜨면 사람이 안 읽는다.
 */
export function 헷갈림주의({ 고른어종, 길이, 날짜, 어종찾기 }) {
  const 목록 = (자료.쌍 && 자료.쌍[고른어종]) || [];
  if (!목록.length || !어종찾기) return [];
  const 오늘 = 날짜 || new Date();
  const 나온것 = [];

  for (const 칸 of 목록) {
    const 실제칸 = 어종찾기(칸.실제);
    if (!실제칸) continue;

    if (칸.금어기놓침 && 금어기인가(실제칸, 오늘)) {
      나온것.push({
        종류: '금어기',
        실제: 칸.실제,
        비율: 칸.비율,
        말: `지금 ${은는(칸.실제)} 금어기예요`,
      });
      continue;                       // 한 어종에 한 줄이면 충분하다
    }

    const 기준 = 실제칸.금지체장 && 실제칸.금지체장.값;
    if (칸.기준높아짐 && 기준 != null && 길이 != null && Number(길이) <= 기준) {
      나온것.push({
        종류: '기준',
        실제: 칸.실제,
        비율: 칸.비율,
        말: `${이었(칸.실제)} ${기준}cm까지는 놓아주셔야 해요`,
      });
    }
  }
  return 나온것;
}
